#!/usr/bin/env python3
"""Draws the brand: Couch hub mark, PurpleTV and YouTube marks, launcher icon and TV banners.

Run `python3 design/brand.py` after changing a mark. Vector drawables are written directly;
the PNGs (launcher icon, TV banners with the real "Couch" wordmark, web icons) are rendered by
Chromium through Playwright (`node design/render_brand.mjs`, started from here).
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
DRAW = RES / "drawable"
WEB = ROOT / "app/src/main/assets/web"
TOKENS = json.loads((ROOT / "design/tokens.json").read_text())["color"]

SQ = "M12,0h24a12,12 0,0 1,12 12v24a12,12 0,0 1,-12 12h-24a12,12 0,0 1,-12 -12v-24a12,12 0,0 1,12 -12z"
# Couch gradient: indigo → violet → pink, from the bottom left to the top right.
HUB_STOPS = [(0, TOKENS["hubDeep"]["value"]), (0.5, TOKENS["hub"]["value"]), (1, TOKENS["hubGlow"]["value"])]

# Couch: a sofa whose backrest carries a play button. (color, path, even-odd fill)
COUCH = [
    ("#FFFFFF", "M17.5,11h13a4.5,4.5 0,0 1,4.5 4.5v10.5h-22v-10.5a4.5,4.5 0,0 1,4.5 -4.5z M21.6,14.4l6.8,4.1l-6.8,4.1z", True),
    ("#FFFFFF", "M11,19a3.5,3.5 0,0 1,3.5 3.5v12.5h-7v-12.5a3.5,3.5 0,0 1,3.5 -3.5z", False),
    ("#FFFFFF", "M37,19a3.5,3.5 0,0 1,3.5 3.5v12.5h-7v-12.5a3.5,3.5 0,0 1,3.5 -3.5z", False),
    ("#FFFFFF", "M13.5,27.3h21v7.7h-21z", False),
    ("#FFFFFF", "M9,35h3.4v2.2a1,1 0,0 1,-1 1h-1.4a1,1 0,0 1,-1 -1z M35.6,35h3.4v2.2a1,1 0,0 1,-1 1h-1.4a1,1 0,0 1,-1 -1z", False),
]
# PurpleTV: a TV with a chat tail and a play triangle.
PURPLETV = [
    ("#FFFFFF", "M11.5,13.3h25a2.7,2.7 0,0 1,2.7 2.7v14.2a2.7,2.7 0,0 1,-2.7 2.7h-13.3l-4.5,4.5v-4.5h-7.2a2.7,2.7 0,0 1,-2.7 -2.7v-14.2a2.7,2.7 0,0 1,2.7 -2.7z M20.9,18.2l8,4.9l-8,4.9z", True),
]
YOUTUBE = [("#FFFFFF", "M19,14.5l15,9.5l-15,9.5z", False)]

TWITCH_BG = TOKENS["twitch"]["value"]
YOUTUBE_BG = TOKENS["youtube"]["value"]


def vector_gradient_attr(x1, y1, x2, y2):
    items = "".join(f'<item android:offset="{o}" android:color="#FF{c[1:]}"/>' for o, c in HUB_STOPS)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1}" '
            f'android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">{items}</gradient></aapt:attr>')


def paths_xml(paths, indent="    "):
    return "\n".join(
        f'{indent}<path android:fillColor="#FF{c[1:]}"{" android:fillType=\"evenOdd\"" if eo else ""} android:pathData="{d}" />'
        for c, d, eo in paths)


def mark(name, comment, bg, paths):
    bg_xml = (f'    <path android:pathData="{SQ}">{vector_gradient_attr(0, 48, 48, 0)}</path>' if bg == "hub"
              else f'    <path android:fillColor="#FF{bg[1:]}" android:pathData="{SQ}" />')
    (DRAW / f"{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by design/brand.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="48dp" android:height="48dp" android:viewportWidth="48" android:viewportHeight="48">
{bg_xml}
{paths_xml(paths)}
</vector>
''')


def svg_mark(bg, paths, rounded=True, gloss=True):
    """A mark as SVG (for the web app and as source of the PNGs)."""
    if bg == "hub":
        stops = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in HUB_STOPS)
        fill = "url(#g)"
        defs = f'<linearGradient id="g" x1="0" y1="48" x2="48" y2="0" gradientUnits="userSpaceOnUse">{stops}</linearGradient>'
    else:
        fill, defs = bg, ""
    # A soft light from the top left gives the flat square some depth.
    defs += ('<radialGradient id="l" cx="10" cy="4" r="40" gradientUnits="userSpaceOnUse">'
             '<stop offset="0" stop-color="#fff" stop-opacity=".28"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>')
    rx = 'rx="12"' if rounded else ""
    body = "".join(f'<path fill="{c}"{" fill-rule=\"evenodd\"" if eo else ""} d="{d}"/>' for c, d, eo in paths)
    light = f'<rect width="48" height="48" {rx} fill="url(#l)"/>' if gloss else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48"><defs>{defs}</defs>'
            f'<rect width="48" height="48" {rx} fill="{fill}"/>{light}{body}</svg>')


def banner_html(icon_svg, title, subtitle, glow):
    """TV home screen banner (320x180 dp) with the real wordmark."""
    return f'''<!doctype html><html><head><style>
html,body{{margin:0;width:320px;height:180px;overflow:hidden;background:#0A0912}}
.b{{position:relative;width:320px;height:180px;display:flex;align-items:center;gap:18px;padding:0 26px;box-sizing:border-box;
  background:radial-gradient(circle at 18% 50%, {glow}66 0, {glow}22 34%, transparent 62%), #0A0912}}
.i{{width:84px;height:84px;flex:none;filter:drop-shadow(0 6px 18px {glow}88)}}.i svg{{width:100%;height:100%;display:block}}
.t{{font-family:"Inter Display","Inter",sans-serif;font-weight:800;font-size:44px;letter-spacing:-1.2px;color:#fff;line-height:1}}
.s{{font-family:"Inter",sans-serif;font-weight:600;font-size:13px;color:#B9B6CC;margin-top:8px;letter-spacing:.2px}}
</style></head><body><div class="b"><div class="i">{icon_svg}</div><div><div class="t">{title}</div><div class="s">{subtitle}</div></div></div></body></html>'''


def render():
    """PNG output through Chromium (Playwright)."""
    hub = svg_mark("hub", COUCH)
    jobs = [
        # Launcher icon for app lists (48 dp → 192 px at xxxhdpi), full bleed without rounding.
        {"html": f'<html><body style="margin:0">{svg_mark("hub", COUCH, rounded=False)}</body></html>', "w": 192, "h": 192, "fit": True,
         "out": str(RES / "drawable-xxxhdpi/ic_launcher.png")},
        {"html": banner_html(hub, "Couch", "Twitch · YouTube · teilen", HUB_STOPS[1][1]), "w": 320, "h": 180, "scale": 2,
         "out": str(RES / "drawable-xhdpi/banner.png")},
        {"html": banner_html(svg_mark(TWITCH_BG, PURPLETV), "PurpleTV", "Twitch auf Couch", TWITCH_BG), "w": 320, "h": 180, "scale": 2,
         "out": str(RES / "drawable-xhdpi/banner_twitch.png")},
        {"html": banner_html(svg_mark(YOUTUBE_BG, YOUTUBE), "YouTube", "auf Couch", YOUTUBE_BG), "w": 320, "h": 180, "scale": 2,
         "out": str(RES / "drawable-xhdpi/banner_youtube.png")},
        # Home screen icons for iPhone and the web app.
        {"html": f'<html><body style="margin:0">{svg_mark("hub", COUCH, rounded=False)}</body></html>', "w": 180, "h": 180, "fit": True,
         "out": str(WEB / "icon-180.png")},
        {"html": f'<html><body style="margin:0">{svg_mark("hub", COUCH, rounded=False)}</body></html>', "w": 512, "h": 512, "fit": True,
         "out": str(WEB / "icon-512.png")},
    ]
    for j in jobs:
        Path(j["out"]).parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["node", str(ROOT / "design/render_brand.mjs")], input=json.dumps(jobs), text=True, check=True)


if __name__ == "__main__":
    mark("mark_hub", "Couch hub mark: a sofa with a play button on the Couch gradient.", "hub", COUCH)
    mark("mark_twitch", "PurpleTV (Twitch app) mark: TV with a chat tail.", TWITCH_BG, PURPLETV)
    mark("mark_youtube", "YouTube app mark inside Couch (stylised play button, not the official logo).", YOUTUBE_BG, YOUTUBE)
    (WEB / "icon.svg").write_text(svg_mark("hub", COUCH) + "\n")
    (WEB / "mark-purpletv.svg").write_text(svg_mark(TWITCH_BG, PURPLETV, gloss=False) + "\n")
    (WEB / "mark-youtube.svg").write_text(svg_mark(YOUTUBE_BG, YOUTUBE, gloss=False) + "\n")
    render()
    print("brand assets written")
