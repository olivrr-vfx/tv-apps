#!/usr/bin/env python3
"""Draws the brand marks (Couch hub, PurpleTV, YouTube) as Android vectors, SVG and PNG icons.

Run `python3 design/brand.py` after changing a mark. Needs Pillow for the PNG icons.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRAW = ROOT / "app/src/main/res/drawable"
WEB = ROOT / "app/src/main/assets/web"

SQ = "M12,0h24a12,12 0,0 1,12 12v24a12,12 0,0 1,-12 12h-24a12,12 0,0 1,-12 -12v-24a12,12 0,0 1,12 -12z"
HUB_STOPS = [(0, "#4B3BD6"), (0.55, "#7C6CFF"), (1, "#22D3EE")]

# Couch: a sofa. Gap between back and seat shows the gradient.
COUCH = [
    ("#FFFFFF", "M15,13h18a3,3 0,0 1,3 3v8h-24v-8a3,3 0,0 1,3 -3z"),
    ("#FFFFFF", "M11,20h1a3,3 0,0 1,3 3v11h-7v-11a3,3 0,0 1,3 -3z"),
    ("#FFFFFF", "M36,20h1a3,3 0,0 1,3 3v11h-7v-11a3,3 0,0 1,3 -3z"),
    ("#FFFFFF", "M15,26h18v8h-18z"),
    ("#FFFFFF", "M10,34h3v3.5h-3z M35,34h3v3.5h-3z"),
]
# PurpleTV: the original app icon, a TV with a chat tail and a play triangle.
PURPLETV = [
    ("#FFFFFF", "M11.5,13.3h25a2.7,2.7 0,0 1,2.7 2.7v14.2a2.7,2.7 0,0 1,-2.7 2.7h-13.3l-4.5,4.5v-4.5h-7.2a2.7,2.7 0,0 1,-2.7 -2.7v-14.2a2.7,2.7 0,0 1,2.7 -2.7z"),
    ("#9147FF", "M20.9,18.2l8,4.9l-8,4.9z"),
]
YOUTUBE = [("#FFFFFF", "M19,14.5l15,9.5l-15,9.5z")]


def vector_gradient_attr(x1, y1, x2, y2):
    items = "".join(f'<item android:offset="{o}" android:color="#FF{c[1:]}"/>' for o, c in HUB_STOPS)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1}" '
            f'android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">{items}</gradient></aapt:attr>')


def paths_xml(paths, indent="    "):
    return "\n".join(f'{indent}<path android:fillColor="#FF{c[1:]}" android:pathData="{d}" />' for c, d in paths)


def mark(name, comment, bg, paths):
    bg_xml = (f'    <path android:pathData="{SQ}">{vector_gradient_attr(0, 48, 48, 0)}</path>' if bg == "hub"
              else f'    <path android:fillColor="#FF{bg[1:]}" android:pathData="{SQ}" />')
    (DRAW / f"{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by design/brand.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="48dp" android:height="48dp" android:viewportWidth="48" android:viewportHeight="48">
{bg_xml}
{paths_xml(paths)}
</vector>
''')


def launcher():
    (DRAW / "ic_launcher.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Couch launcher icon. Generated by design/brand.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="48" android:viewportHeight="48">
    <path android:pathData="M0,0h48v48h-48z">{vector_gradient_attr(0, 48, 48, 0)}</path>
{paths_xml(COUCH)}
</vector>
''')


def banner(name, glow, bg, paths, wordmark_width):
    bg_xml = (f'        <path android:pathData="{SQ}">{vector_gradient_attr(0, 48, 48, 0)}</path>' if bg == "hub"
              else f'        <path android:fillColor="#FF{bg[1:]}" android:pathData="{SQ}" />')
    (DRAW / f"{name}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- TV home screen banner. Generated by design/brand.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="320dp" android:height="180dp" android:viewportWidth="320" android:viewportHeight="180">
    <path android:fillColor="#FF09090E" android:pathData="M0,0h320v180h-320z" />
    <path android:pathData="M0,0h320v180h-320z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="90" android:centerY="90" android:gradientRadius="230">
                <item android:offset="0" android:color="{glow}" />
                <item android:offset="1" android:color="#0009090E" />
            </gradient>
        </aapt:attr>
    </path>
    <group android:translateX="42" android:translateY="42" android:scaleX="2" android:scaleY="2">
{bg_xml}
{paths_xml(paths, "        ")}
    </group>
    <path android:fillColor="#FFF5F5FA" android:pathData="M164,72h{wordmark_width}a6,6 0,0 1,0 12h-{wordmark_width}a6,6 0,0 1,0 -12z" />
    <path android:fillColor="#80A9A9BC" android:pathData="M164,96h76a5,5 0,0 1,0 10h-76a5,5 0,0 1,0 -10z" />
</vector>
''')


def svg():
    stops = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in HUB_STOPS)
    body = "".join(f'<path fill="{c}" d="{d}"/>' for c, d in COUCH)
    (WEB / "icon.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48"><defs><linearGradient id="g" x1="0" y1="48" x2="48" y2="0" '
        f'gradientUnits="userSpaceOnUse">{stops}</linearGradient></defs><rect width="48" height="48" rx="12" fill="url(#g)"/>{body}</svg>\n')
    for name, bg, paths in (("mark-purpletv.svg", "#9147FF", PURPLETV), ("mark-youtube.svg", "#FF2E4D", YOUTUBE)):
        body = "".join(f'<path fill="{c}" d="{d}"/>' for c, d in paths)
        (WEB / name).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48"><rect width="48" height="48" rx="12" fill="{bg}"/>{body}</svg>\n')


def pngs():
    from PIL import Image, ImageDraw
    from svg_path import parse_path_polys
    def grad(t):
        def h(c): return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))
        for (o1, c1), (o2, c2) in zip(HUB_STOPS, HUB_STOPS[1:]):
            if t <= o2:
                f = (t - o1) / (o2 - o1)
                a, b = h(c1), h(c2)
                return tuple(int(a[i] + (b[i] - a[i]) * f) for i in range(3))
        return h(HUB_STOPS[-1][1])
    for size in (180, 512):
        S = size * 4
        img = Image.new("RGB", (S, S))
        px = img.load()
        for y in range(S):
            for x in range(S):
                px[x, y] = grad((x + (S - y)) / (2 * S))
        d = ImageDraw.Draw(img)
        for color, path in COUCH:
            for poly in parse_path_polys(path, S / 48):
                d.polygon(poly, fill=color)
        img.resize((size, size), Image.LANCZOS).save(WEB / f"icon-{size}.png", optimize=True)


if __name__ == "__main__":
    mark("mark_hub", "Couch hub mark: a sofa on the hub gradient.", "hub", COUCH)
    mark("mark_twitch", "PurpleTV (Twitch app) mark: TV with a chat tail.", "#9147FF", PURPLETV)
    mark("mark_youtube", "YouTube app mark inside Couch (stylised play button, not the official logo).", "#FF2E4D", YOUTUBE)
    launcher()
    banner("banner", "#B37C6CFF", "hub", COUCH, 84)
    banner("banner_twitch", "#B39147FF", "#9147FF", PURPLETV, 110)
    banner("banner_youtube", "#B3FF2E4D", "#FF2E4D", YOUTUBE, 104)
    svg()
    pngs()
    print("brand assets written")
